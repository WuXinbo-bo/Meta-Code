import assert from 'node:assert/strict';
import os from 'node:os';
import path from 'node:path';
import { ClaudeBackgroundTasks, claudeUserInput } from '../server/engines/claude/backgroundTasks.ts';
import { ClaudeSessionHandle } from '../server/engines/claude/session.ts';
import { claudeTranscriptTerminalState } from '../server/engines/claude/transcriptLifecycle.ts';
assert.equal(claudeTranscriptTerminalState({type:'user',toolEndsTurn:true,message:{content:[{type:'tool_result',content:'Structured output provided successfully'}]}}),'completed');
assert.equal(claudeTranscriptTerminalState({type:'user',toolEndsTurn:true,message:{content:[{type:'tool_result',is_error:true}]}}),'failed');
assert.equal(claudeTranscriptTerminalState({type:'user',message:{content:[{type:'tool_result',content:'completed'}]}}),undefined);
assert.equal(claudeTranscriptTerminalState({type:'user',toolEndsTurn:true,message:{content:[{type:'text',text:'completed'}]}}),undefined);
const tasks=new ClaudeBackgroundTasks();
tasks.apply({subtype:'task_started',task_id:'ambient',ambient:true});
assert.equal(tasks.mustWait({}),false,'ambient watchers must not keep a user task running');
tasks.apply({subtype:'task_started',task_id:'worker'});
assert.equal(tasks.mustWait({}),true);
tasks.apply({subtype:'task_updated',task_id:'worker',patch:{status:'completed'}});
assert.equal(tasks.mustWait({}),true,'do not close before the completion notification is delivered');
tasks.apply({subtype:'task_notification',task_id:'worker',status:'failed'});
assert.equal(tasks.mustWait({}),false);
tasks.apply({subtype:'background_tasks_changed',tasks:[{task_id:'new'},{task_id:'watch',ambient:true}]});
assert.equal(tasks.activeCount,1);
tasks.apply({subtype:'background_tasks_changed',tasks:[]});
assert.equal(tasks.mustWait({queued_turn_count:1}),true);
assert.equal(tasks.mustWait({queued_turn_count:0}),false);
assert.deepEqual(claudeUserInput('user','human').origin,{kind:'human'});
assert.deepEqual(claudeUserInput('scheduled','auto-continuation').origin,{kind:'auto-continuation'});
assert.equal(claudeUserInput('legacy').origin,undefined);
const events=[];
const handle=new ClaudeSessionHandle({executable:process.execPath,executableArgs:[path.resolve('scripts/fixtures/fake-claude-background.mjs')],cwd:process.cwd(),configDir:os.tmpdir(),permissionMode:'default',disallowNativeAgents:false,signal:new AbortController().signal,outputTimeoutMs:2000,onEvent:event=>events.push(event)});
try {
 handle.send('review','human');
 const result=await handle.nextTurn();
 assert.equal(result.failed,false);
 assert.equal(events.filter(e=>e.type==='turn.completed').length,1,'intermediate native result must not release the process lease');
 assert.ok(events.some(e=>e.rawType==='result.background_wait'));
 assert.ok(events.some(e=>e.type==='assistant'&&e.text.includes('origin=human')));
 assert.ok(!events.some(e=>e.sourceId==='child-read'),'child tools must not pollute the main turn counters');
 assert.equal(events.at(-1).text,'Review consumed');
}finally{handle.close()}
console.log('Claude background completion, authoritative snapshots, ambient filtering and input provenance passed');
