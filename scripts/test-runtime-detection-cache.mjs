import assert from 'node:assert/strict';
import { RuntimeDetectionCache } from '../server/runtime/detectionCache.ts';
const deferred = () => { let resolve, reject; const promise = new Promise((a, b) => { resolve=a; reject=b; }); return {promise, resolve, reject}; };
let now = 0;
const probes = [], errors = [];
const cache = new RuntimeDetectionCache(() => { const p = deferred(); probes.push(p); return p.promise; }, 100, e => errors.push(e), () => now);
const tick = async () => { for(let i=0;i<10;i++) await Promise.resolve(); };
const first = cache.get(), concurrent = cache.get();
await tick(); assert.equal(probes.length, 1);
probes[0].resolve('missing');
assert.equal(await first, 'missing'); assert.equal(await concurrent, 'missing');
now = 101;
assert.equal(await cache.get(false, true), 'missing');
await tick(); assert.equal(probes.length, 2);
cache.invalidate(); assert.equal(cache.peek(), null);
const selected = cache.get(false, true);
await tick(); assert.equal(probes.length, 3);
probes[2].resolve('new-cli'); assert.equal(await selected, 'new-cli');
probes[1].resolve('old-cli'); await tick();
assert.equal(cache.peek(), 'new-cli');
assert.equal(await cache.get(), 'new-cli');
const oldWaiter = cache.get(true); await tick();
cache.invalidate();
const newWaiter = cache.get(); await tick();
probes[3].reject(new Error('removed old executable'));
probes[4].resolve('third-cli');
assert.equal(await oldWaiter, 'third-cli'); assert.equal(await newWaiter, 'third-cli');
assert.equal(errors.length, 0);
now += 101;
assert.equal(await cache.get(false, true), 'third-cli'); await tick();
probes[5].reject(new Error('temporary probe failure')); await tick();
assert.equal(errors.length, 1); assert.equal(cache.peek(), 'third-cli');
const retry = cache.get(true); await tick(); probes[6].resolve('recovered');
assert.equal(await retry, 'recovered');
console.log('Runtime detection: deduplication, expiry, selection invalidation, late result/error isolation and retry passed');
