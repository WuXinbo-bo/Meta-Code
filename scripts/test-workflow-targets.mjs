import assert from "node:assert/strict";
import fs from "node:fs/promises";
import os from "node:os";
import path from "node:path";
import { execFile } from "node:child_process";
import { promisify } from "node:util";
import { WorkflowTargetService } from "../server/plugins/orchestration/targets.ts";
import { createWorktree } from "../server/git/worktreeManager.ts";

const exec = promisify(execFile);
const directory = await fs.mkdtemp(path.join(os.tmpdir(), "metacode-targets-"));
const repository = path.join(directory, "repo");
const runtime = path.join(directory, "runtime");
const git = async (root, ...args) => String((await exec("git", ["-C", root, ...args])).stdout).trim();
const input = (runId, executionTarget = "workspace", workspaceRoot = repository) => ({ runId, executionTarget, ownerUserId: "owner", workspaceId: "workspace", workspaceRoot });
try {
  await fs.mkdir(repository);
  await git(repository, "init", "-b", "main");
  await git(repository, "config", "user.name", "Test");
  await git(repository, "config", "user.email", "test@example.com");
  await fs.mkdir(path.join(repository, "src"));
  await fs.writeFile(path.join(repository, "README.md"), "initial\n");
  await fs.writeFile(path.join(repository, "obsolete.txt"), "old\n");
  await fs.writeFile(path.join(repository, "src", "index.js"), "initial\n");
  await git(repository, "add", ".");
  await git(repository, "commit", "-m", "initial");
  const service = new WorkflowTargetService(runtime);
  const workspace = await service.prepare(input("workspace-run"));
  assert.equal(workspace.executionRoot, await fs.realpath(repository));
  assert.deepEqual(await fs.readdir(repository), [".git", "README.md", "obsolete.txt", "src"]);
  const isolated = await service.prepare(input("isolated-run", "isolated"));
  assert.equal(path.relative(await fs.realpath(runtime), isolated.executionRoot), path.join("targets", "isolated-run"));
  await service.rollbackPrepared("isolated-run", "owner");
  await assert.rejects(() => fs.access(isolated.executionRoot));
  await assert.rejects(() => service.prepare({ ...input("bad-isolation", "isolated"), executionRoot: repository }), /插件管理/);
  assert.equal(await service.preferredBranchTarget(repository), "worktree");
  assert.equal(await service.preferredBranchTarget(runtime), "isolated");
  const target = await service.prepare(input("worktree-run", "worktree"));
  service.confirmPrepared("worktree-run", "owner");
  assert.equal(target.worktreeId, "worktree-run");
  assert.equal(await service.get("worktree-run", "other"), null);
  await assert.rejects(() => service.prepare({ ...input("worktree-run", "worktree"), ownerUserId: "other" }), /已经绑定/);
  await fs.writeFile(path.join(target.executionRoot, "README.md"), "updated\n");
  await git(target.executionRoot, "add", "README.md");
  await fs.unlink(path.join(target.executionRoot, "obsolete.txt"));
  await fs.writeFile(path.join(target.executionRoot, "new.txt"), "untracked result\n");
  await fs.writeFile(path.join(target.executionRoot, "binary file.bin"), Buffer.from([0, 255, 1, 128]));
  const preview = await service.compare("worktree-run", "owner");
  assert.equal(preview.sourceDirty, true);
  assert.deepEqual(preview.changedFiles.sort(), ["README.md", "binary file.bin", "new.txt", "obsolete.txt"]);
  await assert.rejects(() => service.integrate("worktree-run", "owner", { expectedRevision: 1, previewDigest: preview.previewDigest }), /确认/);
  await fs.writeFile(path.join(target.executionRoot, "new.txt"), "changed after preview\n");
  await assert.rejects(() => service.integrate("worktree-run", "owner", { expectedRevision: 1, previewDigest: preview.previewDigest, snapshotChanges: true }), /已变化/);
  await fs.writeFile(path.join(repository, "local.txt"), "user changes\n");
  assert.equal((await service.compare("worktree-run", "owner")).status, "blocked");
  await fs.unlink(path.join(repository, "local.txt"));
  const current = await service.compare("worktree-run", "owner");
  const sourceHead = await git(target.executionRoot, "rev-parse", "HEAD");
  const sourceIndex = await git(target.executionRoot, "diff", "--cached");
  const integrated = await service.integrate("worktree-run", "owner", { expectedRevision: 1, previewDigest: current.previewDigest, snapshotChanges: true });
  assert.equal(integrated.status, "integrated");
  assert.equal(await fs.readFile(path.join(repository, "new.txt"), "utf8"), "changed after preview\n");
  assert.deepEqual(await fs.readFile(path.join(repository, "binary file.bin")), Buffer.from([0, 255, 1, 128]));
  await assert.rejects(() => fs.access(path.join(repository, "obsolete.txt")));
  assert.equal(await git(target.executionRoot, "rev-parse", "HEAD"), sourceHead);
  assert.equal(await git(target.executionRoot, "diff", "--cached"), sourceIndex);
  assert.equal((await new WorkflowTargetService(runtime).get("worktree-run", "owner")).revision, 2);
  const repeatedPreview = await service.compare("worktree-run", "owner");
  assert.equal(repeatedPreview.status, "already_up_to_date");
  const repeatHead = await git(repository, "rev-parse", "HEAD");
  assert.equal((await service.integrate("worktree-run", "owner", { expectedRevision: 2, previewDigest: repeatedPreview.previewDigest, snapshotChanges: true })).status, "already_up_to_date");
  assert.equal(await git(repository, "rev-parse", "HEAD"), repeatHead);
  const failed = await service.prepare(input("failed-run", "worktree"));
  await service.rollbackPrepared("failed-run", "owner");
  await assert.rejects(() => fs.access(failed.executionRoot));
  const scoped = await service.prepare(input("subdirectory-run", "worktree", path.join(repository, "src")));
  service.confirmPrepared("subdirectory-run", "owner");
  assert.equal(path.basename(scoped.executionRoot), "src");
  await fs.writeFile(path.join(scoped.executionRoot, "index.js"), "module change\n");
  await fs.writeFile(path.join(path.dirname(scoped.executionRoot), "README.md"), "outside workspace\n");
  assert.equal((await service.compare("subdirectory-run", "owner")).status, "blocked");
  const existingRoot = path.join(directory, "existing-worktree");
  await createWorktree({ workspaceRoot: repository, worktreePath: existingRoot, branch: "existing-plan" });
  await fs.writeFile(path.join(existingRoot, "before-binding.txt"), "pre-existing plan commit\n");
  await git(existingRoot, "add", "before-binding.txt");
  await git(existingRoot, "commit", "-m", "work before task binding");
  const existing = await service.prepare({ ...input("existing-run", "worktree"), executionRoot: existingRoot });
  service.confirmPrepared("existing-run", "owner");
  const existingPreview = await service.compare("existing-run", "owner");
  assert.ok(existingPreview.changedFiles.includes("before-binding.txt"));
  assert.ok(existingPreview.committedDiff.includes("pre-existing plan commit"));
  assert.equal(existing.executionRoot, await fs.realpath(existingRoot));

  await fs.writeFile(path.join(repository, ".gitignore"), "result.txt\nsrc/forced result.txt\n");
  await git(repository, "add", ".gitignore");
  await git(repository, "commit", "-m", "Ignore generated results by default");
  const forced = await service.prepare(input("force-ignored-run", "worktree"));
  service.confirmPrepared("force-ignored-run", "owner");
  await fs.writeFile(path.join(forced.executionRoot, "result.txt"), "deliberately tracked generated result\n");
  await git(forced.executionRoot, "add", "-f", "result.txt");
  await git(forced.executionRoot, "update-index", "--split-index");
  assert.ok(await git(forced.executionRoot, "rev-parse", "--shared-index-path"), "fixture must exercise a split source index");
  const forcedPreview = await service.compare("force-ignored-run", "owner");
  assert.ok(forcedPreview.changedFiles.includes("result.txt"));
  const forcedHead = await git(forced.executionRoot, "rev-parse", "HEAD");
  const forcedStage = await git(forced.executionRoot, "ls-files", "--stage", "-z");
  const forcedStagedDiff = await git(forced.executionRoot, "diff", "--cached", "--binary");
  const forcedResult = await service.integrate("force-ignored-run", "owner", { expectedRevision: 1, previewDigest: forcedPreview.previewDigest, snapshotChanges: true });
  assert.equal(forcedResult.status, "integrated");
  assert.equal(await fs.readFile(path.join(repository, "result.txt"), "utf8"), "deliberately tracked generated result\n", "git add -f deliverables must survive snapshot integration");
  assert.equal(await git(forced.executionRoot, "rev-parse", "HEAD"), forcedHead);
  assert.equal(await git(forced.executionRoot, "ls-files", "--stage", "-z"), forcedStage, "source staging entries remain intact, including a split index");
  assert.equal(await git(forced.executionRoot, "diff", "--cached", "--binary"), forcedStagedDiff);

  const forcedScope = await service.prepare(input("force-ignored-scoped-run", "worktree", path.join(repository, "src")));
  service.confirmPrepared("force-ignored-scoped-run", "owner");
  const forcedScopeRoot = path.dirname(forcedScope.executionRoot);
  await fs.writeFile(path.join(forcedScope.executionRoot, "forced result.txt"), "scoped deliberately tracked result\n");
  await git(forcedScopeRoot, "add", "-f", "src/forced result.txt");
  const mainReadme = await fs.readFile(path.join(repository, "README.md"), "utf8");
  await fs.writeFile(path.join(forcedScopeRoot, "README.md"), "staged outside-scope version\n");
  await git(forcedScopeRoot, "add", "README.md");
  await fs.writeFile(path.join(forcedScopeRoot, "README.md"), mainReadme);
  const scopedStage = await git(forcedScopeRoot, "ls-files", "--stage", "-z");
  const forcedScopePreview = await service.compare("force-ignored-scoped-run", "owner");
  assert.equal(forcedScopePreview.status, "ready");
  const scopedResult = await service.integrate("force-ignored-scoped-run", "owner", { expectedRevision: 1, previewDigest: forcedScopePreview.previewDigest, snapshotChanges: true });
  assert.equal(scopedResult.status, "integrated");
  assert.equal(await fs.readFile(path.join(repository, "src", "forced result.txt"), "utf8"), "scoped deliberately tracked result\n");
  assert.equal(await fs.readFile(path.join(repository, "README.md"), "utf8"), mainReadme, "an out-of-scope staged version must not leak into the snapshot");
  assert.equal(await git(forcedScopeRoot, "ls-files", "--stage", "-z"), scopedStage);

  const conflict = await service.prepare(input("unmerged-run", "worktree"));
  service.confirmPrepared("unmerged-run", "owner");
  const conflictRoot = conflict.executionRoot;
  await git(conflictRoot, "checkout", "-b", "conflict-other");
  await fs.writeFile(path.join(conflictRoot, "README.md"), "other conflict version\n");
  await git(conflictRoot, "add", "README.md"); await git(conflictRoot, "commit", "-m", "Other conflict version");
  await git(conflictRoot, "checkout", "metacode/unmerged-run");
  await fs.writeFile(path.join(conflictRoot, "README.md"), "task conflict version\n");
  await git(conflictRoot, "add", "README.md"); await git(conflictRoot, "commit", "-m", "Task conflict version");
  await assert.rejects(() => git(conflictRoot, "merge", "conflict-other"));
  const unmergedPreview = await service.compare("unmerged-run", "owner");
  const unmergedEntries = await git(conflictRoot, "ls-files", "--stage", "-z");
  const targetBeforeConflict = await git(repository, "rev-parse", "HEAD");
  await assert.rejects(() => service.integrate("unmerged-run", "owner", { expectedRevision: 1, previewDigest: unmergedPreview.previewDigest, snapshotChanges: true }), /未解决的合并冲突/);
  assert.equal(await git(repository, "rev-parse", "HEAD"), targetBeforeConflict);
  assert.equal(await git(conflictRoot, "ls-files", "--stage", "-z"), unmergedEntries, "rejecting unresolved source entries must preserve all conflict stages");
  assert.equal((await fs.readdir(runtime)).some((entry) => entry.startsWith("snapshot-") || entry.startsWith("sharedindex.")), false, "temporary standalone indexes must be removed after success and failure");
  console.log("workflow targets: workspace/isolation binding, preview and dirty-target safeguards, snapshot integration preserving ignored forced staging/split-index/scoped boundaries, immutable source index/HEAD and unmerged rejection passed");
} finally { await fs.rm(directory, { recursive: true, force: true }); }
