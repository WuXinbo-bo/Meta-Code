import assert from "node:assert/strict";
import fs from "node:fs/promises";
import os from "node:os";
import path from "node:path";
import { DatabaseSync } from "node:sqlite";
import { WorkflowRepository } from "../dist-server/plugins/orchestration/repository.js";
import { WorkflowStateFiles, calculateWorkflowPlanImpact } from "../dist-server/plugins/orchestration/stateFiles.js";
import { captureWorkspaceSnapshot, captureWorkspaceSnapshotSync, changedWorkspaceFiles } from "../dist-server/plugins/orchestration/enforcement.js";
import { resolveWorkflowResultPath, workflowExecutionRoot } from "../dist-server/plugins/orchestration/executionRoot.js";
import { buildWorkflowFileIntegrity, workflowResultFileIntegrityIssue } from "../dist-server/plugins/orchestration/fileIntegrity.js";
import { normalizeWorkflowNodeResult } from "../dist-server/plugins/orchestration/execution.js";
import { normalizeWorkflowPlan, planSystemPrompt, validateWorkflowPlan } from "../dist-server/plugins/orchestration/plan.js";

const temporary = await fs.mkdtemp(path.join(os.tmpdir(), "metacode-execution-root-"));
try {
  const workspaceRoot = path.join(temporary, "existing-project");
  const runtimeRoot = path.join(temporary, "plugin-runtime");
  await fs.mkdir(workspaceRoot);
  await fs.mkdir(runtimeRoot);
  await fs.writeFile(path.join(workspaceRoot, "input.txt"), "original input");
  const repository = new WorkflowRepository(new DatabaseSync(":memory:"));
  const workflow = repository.create({ ownerUserId: "test-user", workspaceId: "test-workspace", executionTarget: "workspace", executionRoot: workspaceRoot, workspaceRoot, prompt: "修改现有项目", plannerEngine: "codex" });
  assert.equal(workflowExecutionRoot(workflow), workspaceRoot);
  assert.equal(workflow.workDirectory, workspaceRoot);
  assert.equal(workflow.executionTarget, "workspace");
  assert.equal(repository.listNavigation("test-user")[0].executionRoot, workspaceRoot);
  const stateFiles = new WorkflowStateFiles(runtimeRoot);
  stateFiles.sync(workflow);
  assert.deepEqual(await fs.readdir(workspaceRoot), ["input.txt"], "创建编排和状态同步不得在项目中创建任务目录");
  assert.equal(repository.create({ ownerUserId: "test-user", workspaceId: "legacy", workDirectory: workspaceRoot, prompt: "旧任务", plannerEngine: "claude" }).executionTarget, "isolated");
  const plan = normalizeWorkflowPlan({ title: "维护", nodes: [{ id: "edit", title: "编辑", objective: "更新输出", provider: "codex", workspaceAccess: "write", writeScope: ["output.txt"], deliverables: ["output.txt"] }] });
  assert.match(planSystemPrompt([], [], "", 5, undefined, "workspace"), /不得创建任务副本、任务子目录/);
  const rootDeliveryPlan = normalizeWorkflowPlan({ ...plan, finalDelivery: { required: true, directory: ".", primary: "output.txt", format: "text", additional: [], producerNodeId: "edit" } });
  assert.ok(!validateWorkflowPlan(rootDeliveryPlan, new Set()).some((issue) => issue.includes("最终交付路径必须位于")), "根目录现有业务文件应能作为交付物，无需额外目录");
  repository.setPlanning(workflow.id, workflow.ownerUserId, workflow.revision);
  const planned = repository.savePlan(workflow.id, workflow.ownerUserId, plan);
  const approved = repository.approve(workflow.id, workflow.ownerUserId, planned.revision);
  const node = approved.nodes[0];
  const checkpoint = path.join(runtimeRoot, "checkpoints");
  await fs.mkdir(checkpoint);
  const before = await captureWorkspaceSnapshot(workspaceRoot);
  await fs.writeFile(path.join(workspaceRoot, "output.txt"), "delivered");
  const after = await captureWorkspaceSnapshot(workspaceRoot);
  assert.deepEqual(changedWorkspaceFiles(before, after), ["output.txt"]);
  const result = normalizeWorkflowNodeResult({ outcome: "completed", humanSummary: "完成", outputs: [{ id: "output", type: "file", path: "output.txt", description: "业务文件", consumableBy: [] }], changedFiles: ["output.txt"] });
  result.fileIntegrity = buildWorkflowFileIntegrity(approved, node, result, before, after, checkpoint);
  assert.equal(workflowResultFileIntegrityIssue(approved, result), null);
  assert.ok(normalizeWorkflowNodeResult(result).fileIntegrity, "持久化规范化必须保留系统文件版本记录");
  node.status = "completed";
  node.summary = result;
  node.resultDigest = "verified-test-digest";
  repository.updateNode(node);
  repository.updateRun(workflow.id, "needs_review");
  const completed = repository.get(workflow.id, workflow.ownerUserId);
  assert.deepEqual(calculateWorkflowPlanImpact(completed, plan).reused, ["edit"]);
  await fs.writeFile(path.join(workspaceRoot, "input.txt"), "changed input");
  assert.match(workflowResultFileIntegrityIssue(completed, result), /输入文件已变化/);
  assert.deepEqual(calculateWorkflowPlanImpact(completed, plan).rerun, ["edit"]);
  repository.setPlanning(workflow.id, workflow.ownerUserId, completed.revision);
  const changedPlan = repository.savePlan(workflow.id, workflow.ownerUserId, plan);
  assert.equal(repository.approve(workflow.id, workflow.ownerUserId, changedPlan.revision).nodes[0].status, "pending", "审批不得复用文件输入过期的节点");
  await fs.writeFile(path.join(workspaceRoot, "input.txt"), "original input");
  await fs.unlink(path.join(workspaceRoot, "output.txt"));
  assert.match(workflowResultFileIntegrityIssue(approved, result), /产物已被修改或删除/);
  await fs.writeFile(path.join(workspaceRoot, "output.txt"), "delivered");
  assert.deepEqual([...captureWorkspaceSnapshotSync(workspaceRoot)].sort(), [...await captureWorkspaceSnapshot(workspaceRoot)].sort());
  await fs.mkdir(path.join(workspaceRoot, "src"));
  await fs.writeFile(path.join(workspaceRoot, "src", "reference.txt"), "existing reference");
  const wideBefore = await captureWorkspaceSnapshot(workspaceRoot);
  await fs.writeFile(path.join(workspaceRoot, "src", "changed.txt"), "implemented");
  const wideAfter = await captureWorkspaceSnapshot(workspaceRoot);
  const wideNode = { ...node, writeScope: ["src/**"] };
  const wideResult = normalizeWorkflowNodeResult({ outcome: "completed", humanSummary: "完成", outputs: [{ id: "file", type: "file", path: "src/changed.txt", description: "输出", consumableBy: [] }], changedFiles: ["src/changed.txt"] });
  wideResult.fileIntegrity = buildWorkflowFileIntegrity({ ...approved, nodes: [wideNode] }, wideNode, wideResult, wideBefore, wideAfter, checkpoint);
  assert.equal(workflowResultFileIntegrityIssue(approved, wideResult), null);
  await fs.writeFile(path.join(workspaceRoot, "src", "reference.txt"), "externally modified reference");
  assert.match(workflowResultFileIntegrityIssue(approved, wideResult), /输入文件已变化/, "writeScope 内未修改的原文件仍应作为输入检查");
  assert.throws(() => resolveWorkflowResultPath(workflow, "../outside.txt", false), /越出业务执行目录/);
  const outside = path.join(temporary, "outside");
  await fs.mkdir(outside);
  await fs.writeFile(path.join(outside, "secret.txt"), "outside");
  try {
    await fs.symlink(outside, path.join(workspaceRoot, "external"), process.platform === "win32" ? "junction" : "dir");
    assert.ok(changedWorkspaceFiles(wideAfter, await captureWorkspaceSnapshot(workspaceRoot)).includes("external"), "符号链接的新增和变更必须被快照观察到，但不遍历外部目录");
    assert.throws(() => resolveWorkflowResultPath(workflow, "external/secret.txt", true), /符号链接越出/);
    assert.throws(() => resolveWorkflowResultPath(workflow, "external/new.txt", false), /符号链接越出/);
  } catch (error) { if (error.code !== "EPERM") throw error; }
  console.log("Workflow execution roots, external state, file invalidation and realpath boundaries OK");
} finally { await fs.rm(temporary, { recursive: true, force: true }); }
