import assert from "node:assert/strict";
import fs from "node:fs/promises";
import os from "node:os";
import path from "node:path";
import { execFile } from "node:child_process";
import { promisify } from "node:util";
import { checkoutBranch, commitFiles, createBranch, fetchRemote, readBranches, readCommitDiff, readCommits, readGitSnapshot, readRemotes, readWorkspaceDiff, stageFiles, unstageFiles } from "../dist-server/git/service.js";

const run = promisify(execFile);
const root = await fs.mkdtemp(path.join(os.tmpdir(), "metacode-git-"));
await run("git", ["-C", root, "init", "-b", "main"]);
await run("git", ["-C", root, "config", "user.email", "test@example.com"]);
await run("git", ["-C", root, "config", "user.name", "Meta Code Test"]);
await fs.writeFile(path.join(root, "README.md"), "hello\n");
await run("git", ["-C", root, "add", "."]);
await run("git", ["-C", root, "commit", "-m", "initial"]);
const initial = (await run("git", ["-C", root, "rev-parse", "HEAD"])).stdout.trim();
await fs.writeFile(path.join(root, "README.md"), "hello\nworld\n");
await fs.writeFile(path.join(root, "new.txt"), "new\n");
const status = await readGitSnapshot(root);
assert.equal(status.isRepository, true);
assert.equal(status.branch, "main");
assert.equal(status.files.length, 2);
assert.ok(status.files.some((item) => item.path === "README.md"));
assert.ok(status.files.some((item) => item.path === "new.txt" && item.status === "untracked"));
const branches = await readBranches(root);
assert.ok(branches.some((item) => item.name === "main" && item.current));
assert.deepEqual(await readRemotes(root), []);
const commits = await readCommits(root);
assert.equal(commits[0].sha, initial);
assert.equal(commits[0].subject, "initial");
assert.match(await readWorkspaceDiff(root), /world/);
assert.match(await readCommitDiff(root, initial), /hello/);
await stageFiles(root, ["README.md", "new.txt"]);
assert.equal((await readGitSnapshot(root)).files.every((item) => item.staged), true);
await unstageFiles(root, ["new.txt"]);
assert.equal((await readGitSnapshot(root)).files.find((item) => item.path === "new.txt")?.staged, false);
await stageFiles(root, ["new.txt"]);
await commitFiles(root, "second");
await createBranch(root, "feature/git-view");
assert.equal((await readGitSnapshot(root)).branch, "feature/git-view");
await checkoutBranch(root, "main");
assert.equal((await readGitSnapshot(root)).branch, "main");
await assert.rejects(() => fetchRemote(root), /未找到可用的 Git 远程仓库/);
await fs.rm(root, { recursive: true, force: true });
console.log("git read-only service status, branches, graph, and diff passed");
